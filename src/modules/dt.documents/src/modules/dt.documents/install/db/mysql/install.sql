CREATE TABLE dt_doc_document (
    ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    TYPE VARCHAR(16) NOT NULL,
    MATCH_MODE VARCHAR(24) NOT NULL DEFAULT 'legacy',
    NAME VARCHAR(255) NOT NULL,
    LINK_TEXT VARCHAR(255) NOT NULL,
    LINK_TITLE VARCHAR(512) NOT NULL DEFAULT '',
    LINK_ALT VARCHAR(512) NOT NULL DEFAULT '',
    TARGET_URL VARCHAR(1024) NOT NULL,
    IMAGE_URL VARCHAR(1024) NOT NULL DEFAULT '',
    ACTIVE CHAR(1) NOT NULL DEFAULT 'Y',
    SORT_ORDER INT NOT NULL DEFAULT 500,
    LEGACY_ID INT UNSIGNED DEFAULT NULL,
    CREATED_AT DATETIME NOT NULL,
    UPDATED_AT DATETIME NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY ux_dt_doc_legacy (LEGACY_ID),
    KEY ix_dt_doc_active_type_sort (ACTIVE, TYPE, SORT_ORDER)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE dt_doc_brand (
    DOCUMENT_ID INT UNSIGNED NOT NULL,
    BRAND VARCHAR(191) NOT NULL,
    PRIMARY KEY (DOCUMENT_ID, BRAND),
    KEY ix_dt_doc_brand_name (BRAND)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE dt_doc_article (
    DOCUMENT_ID INT UNSIGNED NOT NULL,
    ARTICLE VARCHAR(191) NOT NULL,
    PRIMARY KEY (DOCUMENT_ID, ARTICLE),
    KEY ix_dt_doc_article_name (ARTICLE)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE dt_doc_section (
    DOCUMENT_ID INT UNSIGNED NOT NULL,
    SECTION_ID INT NOT NULL,
    INCLUDE_SUBSECTIONS CHAR(1) NOT NULL DEFAULT 'Y',
    PRIMARY KEY (DOCUMENT_ID, SECTION_ID),
    KEY ix_dt_doc_section (SECTION_ID)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE dt_doc_cache_task (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    DOCUMENT_ID INT UNSIGNED NOT NULL DEFAULT 0,
    KIND CHAR(1) NOT NULL,
    SECTION_ID INT NOT NULL DEFAULT 0,
    INCLUDE_SUBSECTIONS CHAR(1) NOT NULL DEFAULT 'N',
    BRAND VARCHAR(191) NOT NULL DEFAULT '',
    ARTICLES_JSON MEDIUMTEXT NOT NULL,
    LAST_ELEMENT_ID INT UNSIGNED NOT NULL DEFAULT 0,
    PROCESSED INT UNSIGNED NOT NULL DEFAULT 0,
    STATUS CHAR(1) NOT NULL DEFAULT 'N',
    ERROR_TEXT VARCHAR(1024) NOT NULL DEFAULT '',
    CREATED_AT DATETIME NOT NULL,
    UPDATED_AT DATETIME NOT NULL,
    PRIMARY KEY (ID),
    KEY ix_dt_doc_task_status (STATUS, ID),
    KEY ix_dt_doc_task_document (DOCUMENT_ID, ID)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
